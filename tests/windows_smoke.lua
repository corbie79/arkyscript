assert(jit.os == "Windows" and jit.arch == "x64", "expected Windows x64")
assert(jit.status(), "JIT disabled")
local ffi = require("ffi")
assert(ffi.abi("64bit") and ffi.sizeof("void *") == 8 and ffi.sizeof("long") == 4)
ffi.cdef[[unsigned long GetCurrentProcessId(void);]]
assert(ffi.load("kernel32").GetCurrentProcessId() > 0)
local callback = ffi.cast("int (*)(int)", function(n) return n + 5 end)
assert(callback(37) == 42)
callback:free()
jit.flush()
jit.opt.start("hotloop=1")
local sum = 0
for n = 1, 10000 do sum = sum + n end
assert(sum == 50005000)
assert(require("jit.util").traceinfo(1), "no compiled JIT trace")
local co = coroutine.create(function() coroutine.yield(42); return 7 end)
local ok, result = coroutine.resume(co)
assert(ok and result == 42)
ok, result = coroutine.resume(co)
assert(ok and result == 7)
local ok, err = pcall(function() error("expected error") end)
assert(not ok and tostring(err):find("expected error", 1, true))
collectgarbage("collect")
print(jit.version .. ": Windows x64 JIT, FFI, callback, coroutine and error handling OK")

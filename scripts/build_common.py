"""Pinned upstream sources and isolated build directories (Python 3.12+)."""
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def run(*args, **kwargs):
    return subprocess.run([str(arg) for arg in args], check=True, **kwargs)


def output(*args, **kwargs):
    return subprocess.check_output([str(arg) for arg in args], text=True, **kwargs).strip()


def dependencies():
    return json.loads((ROOT / "dependencies.json").read_text())


def validate_revision(revision):
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Use a full 40-character lowercase Git commit SHA.")
    return revision


def repository(name, spec, revision=None):
    """Fetch objects without checking out, resetting, or cleaning upstream files."""
    revision = validate_revision(revision or spec["revision"])
    repo = ROOT / ".deps" / name
    if not repo.exists():
        repo.mkdir(parents=True)
        run("git", "init", "--quiet", repo)
        run("git", "-C", repo, "remote", "add", "origin", spec["url"])
    if output("git", "-C", repo, "remote", "get-url", "origin") != spec["url"]:
        raise RuntimeError(f"{repo}: origin differs from dependencies.json; refusing to change it")
    if output("git", "-C", repo, "status", "--porcelain", "--untracked-files=no"):
        raise RuntimeError(f"{repo}: tracked files have local changes; preserve them before building")
    available = subprocess.run(
        ["git", "-C", str(repo), "cat-file", "-e", revision + "^{commit}"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    if available.returncode:
        run("git", "-C", repo, "fetch", "--depth", "1", spec["url"], revision)
    return repo


def snapshot(repo, revision, destination):
    """Only committed files enter builds; old objects/generated headers cannot leak in."""
    validate_revision(revision)
    archive = subprocess.check_output(["git", "-C", str(repo), "archive", revision])
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        tar.extractall(destination, filter="data")
    timestamp = output("git", "-C", repo, "show", "-s", "--format=%ct", revision)
    (destination / ".relver").write_text(timestamp + "\n")
    return timestamp


def write_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
        json.dump(data, handle, indent=2)
        handle.write("\n")
    temporary.chmod(path.stat().st_mode & 0o777 if path.exists() else 0o644)
    os.replace(temporary, path)


def publish_tree(source, destination):
    """Replace only directories previously generated by this build system."""
    marker = ".tynex-build"
    (source / marker).write_text("Generated by scripts/build_common.py\n")
    if destination.exists():
        # Recognize managed outputs from before the project rename.
        if not (destination / marker).is_file() and not (destination / ".tljit-build").is_file():
            raise RuntimeError(f"Refusing to replace an unmanaged directory: {destination}")
        backup = source.parent / "previous-output"
        destination.rename(backup)
        try:
            source.rename(destination)
        except BaseException:
            backup.rename(destination)
            raise
        shutil.rmtree(backup)
    else:
        source.rename(destination)


def find_tool(name, override=None):
    if override:
        found = shutil.which(override)
        if not found:
            raise RuntimeError(f"Tool not found: {override}")
        return found
    found = shutil.which(name)
    if found:
        return found
    for prefix in ("/opt/homebrew", "/usr/local"):
        for formula in ("llvm", "lld", "xwin"):
            path = Path(prefix) / "opt" / formula / "bin" / name
            if path.is_file():
                return str(path)
    raise RuntimeError(f"Missing {name}; install LLVM, LLD and xwin, or set its tool override.")

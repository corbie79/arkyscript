use serde::{Deserialize, Serialize};
use std::{
    ffi::OsString,
    fs,
    path::{Path, PathBuf},
    process::Command,
};
use tynex_compiler::source_map::{Emitter, SourceMap};

#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct Location {
    pub line: usize,
    pub column: usize,
}
#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct FileMap {
    pub original: PathBuf,
    pub generated: PathBuf,
    /// One-based original positions indexed by zero-based generated line.
    pub lines: Vec<Option<Location>>,
}
#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct DebugMap {
    pub version: u8,
    pub files: Vec<FileMap>,
}

/// Build the code and map together so the debugger and runtime manifest use
/// exactly the same generated positions. Direct execution keeps helper code on
/// source line one; bundles isolate it because Lua hooks report only a line,
/// and a helper sharing that line must not trigger a user breakpoint.
pub fn emit(lua: &str, map: &SourceMap) -> Emitter {
    let mut emitter = Emitter::default();
    emitter.helper("-- Generated by Tynex. Edit the original source.\n-- Source locations are recorded in the adjacent .map file.\n");
    let first = map
        .mappings
        .iter()
        .find(|mapping| mapping.original.is_some());
    if let Some(first) =
        first.filter(|first| first.generated.line == 0 && first.generated.column > 0)
    {
        let column = first.generated.column;
        let mut utf16 = 0;
        let split = lua
            .char_indices()
            .find_map(|(byte, ch)| {
                if utf16 == column {
                    Some(byte)
                } else {
                    utf16 += ch.len_utf16();
                    None
                }
            })
            .expect("source map positions are UTF-16 character boundaries");
        emitter.helper(&lua[..split]);
        emitter.helper("\n");
        let mut rest = map.clone();
        rest.mappings
            .retain(|mapping| mapping.generated >= first.generated);
        for mapping in &mut rest.mappings {
            if mapping.generated.line == 0 {
                mapping.generated.column -= column;
            }
        }
        if rest.end.line == 0 {
            rest.end.column -= column;
        }
        emitter.append(&lua[split..], &rest);
    } else {
        emitter.append(lua, map);
    }
    emitter
}

pub fn write(
    project: &crate::project::Project,
    entry: &Path,
    directory: &Path,
) -> Result<(), String> {
    fs::create_dir_all(directory).map_err(|e| e.to_string())?;
    let directory = crate::pathutil::canonicalize(directory).map_err(|e| e.to_string())?;
    let marker = directory.join(".tynex-bundle");
    let legacy_marker = directory.join(".tljit-bundle");
    if !marker.is_file()
        && !legacy_marker.is_file()
        && fs::read_dir(&directory)
            .map_err(|e| e.to_string())?
            .next()
            .is_some()
    {
        return Err("bundle output must be an empty directory or an existing Tynex bundle".into());
    }
    if project.units.keys().any(|p| p.starts_with(&directory)) {
        return Err("bundle output must not contain original sources".into());
    }
    fs::write(marker, "Tynex bundle v1\n").map_err(|e| e.to_string())?;
    let mut map = DebugMap {
        version: 1,
        files: vec![],
    };
    for (index, (path, unit)) in project.units.iter().enumerate() {
        let Some(lua) = &unit.lua else { continue };
        let emitter = emit(
            lua,
            unit.source_map
                .as_ref()
                .ok_or("missing compiler source map")?,
        );
        let generated = directory.join(format!("module-{index}.lua"));
        let mut lines = vec![None; emitter.map.end.line + 1];
        for mapping in &emitter.map.mappings {
            if let Some(original) = mapping.original {
                let line = &mut lines[mapping.generated.line];
                if line.is_none() {
                    *line = Some(Location {
                        line: original.line + 1,
                        column: original.column + 1,
                    });
                }
            }
        }
        let v3 = serde_json::json!({"version":3,"file":generated.file_name().map(|name|name.to_string_lossy()),"sources":[path.to_string_lossy().replace('\\', "/")],
            "sourcesContent":[String::from_utf8_lossy(&unit.source)],"names":[],"mappings":emitter.map.v3_mappings()});
        fs::write(&generated, emitter.code).map_err(|e| e.to_string())?;
        fs::write(
            generated.with_extension("lua.map"),
            serde_json::to_vec(&v3).unwrap(),
        )
        .map_err(|e| e.to_string())?;
        map.files.push(FileMap {
            original: path.clone(),
            generated,
            lines,
        });
    }
    crate::write_manifest(project, entry, &directory, true)?;
    fs::write(
        directory.join("runner.lua"),
        include_str!("../../../runtime/runner.lua"),
    )
    .map_err(|e| e.to_string())?;
    fs::write(
        directory.join("debug-map.json"),
        serde_json::to_vec_pretty(&map).unwrap(),
    )
    .map_err(|e| e.to_string())?;
    if legacy_marker.is_file() {
        fs::remove_file(legacy_marker).map_err(|e| e.to_string())?;
    }
    Ok(())
}
pub fn execute(directory: &Path, debug: bool, args: Vec<OsString>) -> Result<u8, String> {
    let directory = crate::pathutil::canonicalize(directory).map_err(|e| e.to_string())?;
    if !directory.join(".tynex-bundle").is_file() {
        return Err("not a Tynex bundle".into());
    }
    let engine = crate::runtime()?;
    let status = Command::new(&engine)
        .arg(directory.join("runner.lua"))
        .arg(if debug { "debug" } else { "run" })
        .arg(directory.join("manifest.lua"))
        .args(args)
        .env("TYNEX_LUAJIT_DIR", engine.parent().unwrap())
        .status()
        .map_err(|e| e.to_string())?;
    Ok(status
        .code()
        .and_then(|n| u8::try_from(n).ok())
        .unwrap_or(1))
}

#[cfg(test)]
mod tests {
    use super::*;
    use tynex_compiler::{Mode, compile, source_map::Position};

    #[test]
    fn class_helpers_have_an_unmapped_line_separate_from_class_and_method_code() {
        let source = "class Item\n n: number = 42\n function get(): number\n  return self.n\n end\nend\nprint(Item {}:get())\n";
        let compiled = compile(source, Mode::Strict, true).unwrap();
        assert_eq!(compiled.lua.lines().count(), source.lines().count());
        let output = emit(&compiled.lua, &compiled.source_map);
        assert_eq!(output.code.lines().count(), source.lines().count() + 3);
        for line in 0..3 {
            assert_eq!(
                output.map.original_position(Position { line, column: 0 }),
                None
            );
        }
        for original_line in 0..source.lines().count() {
            assert_eq!(
                output
                    .map
                    .original_position(Position {
                        line: original_line + 3,
                        column: 0,
                    })
                    .unwrap()
                    .line,
                original_line
            );
        }
        assert!(
            output
                .code
                .lines()
                .nth(2)
                .unwrap()
                .contains("__tynex_class")
        );
        assert!(
            output
                .code
                .lines()
                .nth(3)
                .unwrap()
                .starts_with("local Item")
        );
        assert_eq!(output.code.lines().nth(6).unwrap(), "  return self.n");
    }

    #[test]
    fn source_without_helpers_keeps_two_metadata_lines() {
        let source = "local n: number = 42\nprint(n)\n";
        let compiled = compile(source, Mode::Strict, true).unwrap();
        let output = emit(&compiled.lua, &compiled.source_map);
        assert_eq!(output.code.lines().count(), source.lines().count() + 2);
        assert_eq!(
            output
                .map
                .original_position(Position { line: 2, column: 0 }),
            Some(Position { line: 0, column: 0 })
        );
    }

    #[test]
    fn helper_split_uses_utf16_columns_and_retains_same_line_segments() {
        let mut source = Emitter::default();
        source.helper("local emoji = '😀'; ");
        source.copied("local n", Position::default());
        source.lowered(" ", Position { line: 0, column: 7 });
        source.copied(
            " = 1",
            Position {
                line: 0,
                column: 15,
            },
        );
        let output = emit(&source.code, &source.map);
        assert_eq!(output.code.lines().nth(2).unwrap(), "local emoji = '😀'; ");
        assert_eq!(output.code.lines().nth(3).unwrap(), "local n  = 1");
        assert_eq!(
            output.map.end,
            Position {
                line: 3,
                column: 12
            }
        );
        assert_eq!(
            output
                .map
                .original_position(Position { line: 3, column: 8 }),
            Some(Position {
                line: 0,
                column: 15
            })
        );
    }
}
